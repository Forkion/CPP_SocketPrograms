#include <arpa/inet.h>
#include <signal.h>
#include <chrono>

#include "../../app_gen/hdr/app.hpp"
#include "../../lib/hdr/lib.hpp"

// Программа №1

// Должна состоять из двух потоков и одного общего буфера.

// Поток 1.  Принимает строку, которую введет пользователь. Должна быть
// проверка, что строка состоит только из цифр и не превышает 64 символа. После
// проверки строка передается на обработку функции 1. Затем обработанная строка
// помещается в общий буфер и поток должен ожидать дальнейшего ввода
// пользователя.

// Поток 2. Должен обрабатывать данные которые помещаются в общий буфер. После
// получения данных общий буфер затирается. Поток должен вывести полученные
// данные на экран, а также передать эти данные функции
// 2.  Значение, возвращенное функцией, передать в Программу №2. После этого
// поток ожидает следующие данные.

// Примечание №1 по Программе №1: Взаимодействие потоков должно быть
// синхронизировано, поток №2 не должен постоянно опрашивать общий буфер.

// Примечание №2 по Программе №1: Работа программы должна быть максимально
// независима от статуса запуска программы №2. Это значит, что внезапная
// остановка программы №2 не должна приводить к немедленным проблемам ввода у
// пользователя. При перезапуске программы №2 необходимо произвести
// передподключение.

/**
 * @class app1
 * @brief Класс клиентского приложения (Программа №1).
 * Наследуется от базовог класса app_gen
 * @details Реализует многопоточное приложение для ввода, обработки и отправки
 * данных через сокет. Использует два потока: ввод/сортировка и
 * обработка/отправка.
 */
class app1 : public app_gen {
 private:
  std::mutex mtx;  ///< Мьютекс для синхронизации доступа к общему буферу
  std::condition_variable
      cv;  ///< Условная переменная для уведомления о новых данных
  bool buffer_status;  ///< Флаг наличия данных в буфере (true - данные готовы)

  /**
   * @brief Обработка ошибки отправки
   * @details Закрывает сокет, сбрасывает дескриптор и устанавливает флаг
   * buffer_status = true для повторной попытки отправки
   */
  void error() noexcept;

 public:
  /**
   * @brief Конструктор по умолчанию
   * @details Инициализирует buffer_status = false, вызывает конструктор app_gen
   */
  app1();

  /**
   * @brief Поток ввода и сортировки данных
   * @details Бесконечный цикл:
   * - Запрашивает ввод строки через init()
   * - Проверяет на пустую строку
   * - Сортирует элементы по убыванию, заменяя четные на "KB"
   * (lib::counting_sort)
   * - При вводе "exit" устанавливает app_exit = true и завершает поток
   * - Записывает данные в общий буфер с синхронизацией через мьютекс
   * - Устанавливает buffer_status = true и уведомляет поток обработки
   */
  void func_thread1();

  /**
   * @brief Поток обработки и отправки данных
   * @details Бесконечный цикл:
   * - Ожидает данные от func_thread1 через condition_variable
   * - Проверяет наличие соединения, при отсутствии вызывает reconnect()
   * - Выводит данные на экран
   * - Вычисляет сумму цифр из буфера через lib::sum()
   * - Отправляет данные в программу 2 в формате: [размер][данные][сумма]
   * - При ошибке отправки вызывает error()
   * - Очищает буфер и сбрасывает buffer_status = false
   */
  void func_thread2();

  /**
   * @brief Подключение к серверу
   * @return true если подключение успешно, false в противном случае
   * @details Создает сокет и пытается подключиться к серверу по адресу
   * 127.0.0.1:32929 Если сокет уже открыт, закрывает его перед созданием нового
   */
  bool connect_to_server();

  /**
   * @brief Переподключение к серверу
   * @details Вызывает connect_to_server() в цикле до установления соединения
   * Выводит сообщение о недоступности сервера каждые 3 секунды
   */
  void reconnect();
};
